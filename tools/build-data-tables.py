#!/usr/bin/env python3
"""Rebuild the lookup tables embedded in index.html from the vendored skill data.

The single-file web app cannot fetch skills/geo-sleuth/data/*.json (GitHub Pages
serves it, but a file:// copy would break), so the three lookup tables are inlined
as compact arrays. Run this after refreshing the skill data with
`uv run skills/geo-sleuth/scripts/refresh.py`, then re-assemble the page.

Usage:
    python3 tools/build-data-tables.py            # rewrite the marker block in index.html
    python3 tools/build-data-tables.py --check    # exit 1 if the block is stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "skills" / "geo-sleuth" / "data"
PAGE = ROOT / "index.html"
START = "<script>\n/* ==== DATA-TABLES-START ==== */"
END = "/* ==== DATA-TABLES-END ==== */\n</script>"


def compact(rows: list[list[str]]) -> str:
    return json.dumps(rows, ensure_ascii=False, separators=(",", ":"))


def build_block() -> str:
    calling = json.loads((DATA / "calling_codes.json").read_text(encoding="utf-8"))
    driving = json.loads((DATA / "driving_side.json").read_text(encoding="utf-8"))
    territories = json.loads((DATA / "territories.json").read_text(encoding="utf-8"))

    rows_cc: list[list[str]] = []
    for prefix, entries in calling.items():
        if prefix == "_meta":
            continue
        digits = prefix.replace("-", "")
        for entry in entries:
            rows_cc.append([digits, prefix, entry.get("country", ""), entry.get("utc", "")])
    rows_cc.sort(key=lambda r: (len(r[0]), r[0]))

    rows_ds: list[list[str]] = []
    for country, info in driving.items():
        if country == "_meta":
            continue
        note = (info.get("note") or "").strip()
        if len(note) > 110:
            note = note[:107] + "..."
        rows_ds.append([country, info.get("side", ""), info.get("switched", ""), note])
    rows_ds.sort(key=lambda r: r[0])

    rows_ter: list[list[str]] = []
    for entries in territories.get("by_sovereign", {}).values():
        for t in entries:
            rows_ter.append([t.get("name", ""), t.get("sovereign", ""), t.get("region", ""), t.get("subregion", ""), t.get("status", "")])
    rows_ter.sort(key=lambda r: r[0])

    return "\n".join(
        [
            START,
            "/* Generated by tools/build-data-tables.py. Do not edit by hand.",
            "   calling codes [digits, printed prefix, country, UTC offset]",
            "   driving side [country, side, changed in, note]",
            "   territories [name, sovereign, region, subregion, status] */",
            f"const DATA_CALLING_CODES = {compact(rows_cc)};",
            f"const DATA_DRIVING_SIDE = {compact(rows_ds)};",
            f"const DATA_TERRITORIES = {compact(rows_ter)};",
            END,
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the page block is current")
    args = parser.parse_args()

    page = PAGE.read_text(encoding="utf-8")
    block = build_block()
    if START not in page or END not in page:
        print("marker block not found in index.html", file=sys.stderr)
        return 2
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    current = pattern.search(page).group(0)
    if args.check:
        if current != block:
            print("index.html lookup tables are stale; run tools/build-data-tables.py", file=sys.stderr)
            return 1
        print("index.html lookup tables are current")
        return 0
    if current != block:
        PAGE.write_text(pattern.sub(lambda _: block, page, count=1), encoding="utf-8")
        print("rewrote the lookup tables in index.html")
    else:
        print("lookup tables already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
